import { useNavigate } from "react-router-dom";
import { useState } from "react";
import { useClaim } from "../context/ClaimContext";

const DEMO_POLICIES = [
  { no: "AS-PLC-100231", vehicle: "Swift 2021", idv: "₹4,50,000" },
  { no: "AS-PLC-100232", vehicle: "City 2018", idv: "₹3,80,000" },
  { no: "AS-PLC-100233", vehicle: "Seltos 2023", idv: "₹9,00,000" },
];

function todayString() {
  const d = new Date();
  return d.toISOString().slice(0, 10);
}

export default function Verify() {
  const navigate = useNavigate();
  
  // Bring in the API functions from your context!
  const { verifyPolicy, startClaim, busy } = useClaim();

  const [policyNo, setPolicyNo] = useState("");
  const [regNo, setRegNo] = useState("");
  const [mobile, setMobile] = useState("");
  const [incidentDate, setIncidentDate] = useState(todayString);

  // OTP state
  const [otpSent, setOtpSent] = useState(false);
  const [otpValue, setOtpValue] = useState("");
  const [otpAttempts, setOtpAttempts] = useState(0);
  const [otpError, setOtpError] = useState("");
  const [verified, setVerified] = useState(false);
  const [apiError, setApiError] = useState("");

  // Demo helper
  const [showDemo, setShowDemo] = useState(false);

  function handleSendOtp() {
    if (!policyNo.trim() || !regNo.trim() || !mobile.trim()) return;
    setOtpSent(true);
    setOtpValue("");
    setOtpError("");
  }

  function handleVerifyOtp() {
    if (otpValue === "123456") {
      setVerified(true);
      setOtpError("");
    } else {
      const remaining = 2 - (otpAttempts + 1);
      if (remaining <= 0) {
        setOtpError("Too many failed attempts. Please start over.");
      } else {
        setOtpError(`Invalid OTP. ${remaining} attempt(s) remaining.`);
      }
      setOtpAttempts((p) => p + 1);
    }
  }

  // The missing bridge to your Python backend
  async function handleContinue() {
    setApiError("");
    try {
      // 1. Tell Python to verify the policy
      await verifyPolicy({ policyNo, regNo, mobile });
      // 2. Tell Python to create the claim in memory
      const newClaim = await startClaim();
      // 3. Navigate using the REAL claim ID generated by Python, not the policy number
      navigate(`/claims/${newClaim.id}/upload`);
    } catch (err: any) {
      setApiError(err.message || "Failed to connect to backend.");
    }
  }

  function resetForm() {
    setPolicyNo("");
    setRegNo("");
    setMobile("");
    setIncidentDate(todayString());
    setOtpSent(false);
    setOtpValue("");
    setOtpAttempts(0);
    setOtpError("");
    setVerified(false);
    setApiError("");
  }

  const otpLocked = otpAttempts >= 3;

  return (
    <div className="mx-auto max-w-xl py-12">
      <h1 className="text-2xl font-bold">Verify your policy</h1>
      <p className="mt-1 text-sm text-[#4A5B6B]">
        Enter your policy number and registration to get started.
      </p>

      {/* Demo helper */}
      <div className="mt-6 rounded-lg border border-amber-300 bg-amber-50">
        <button
          onClick={() => setShowDemo((p) => !p)}
          className="flex w-full items-center justify-between px-4 py-2 text-sm font-medium text-amber-800"
        >
          <span>📋 Demo helper</span>
          <span>{showDemo ? "▲" : "▼"}</span>
        </button>
        {showDemo && (
          <div className="border-t border-amber-200 px-4 py-3 text-sm text-amber-900">
            <p className="mb-2 font-medium">Copy a demo policy:</p>
            <table className="w-full text-left text-xs">
              <thead>
                <tr className="border-b border-amber-200">
                  <th className="py-1 pr-2">Policy No</th>
                  <th className="py-1 pr-2">Vehicle</th>
                  <th className="py-1">IDV</th>
                </tr>
              </thead>
              <tbody>
                {DEMO_POLICIES.map((p) => (
                  <tr
                    key={p.no}
                    className="cursor-pointer border-b border-amber-100 hover:bg-amber-100"
                    onClick={() => {
                      setPolicyNo(p.no);
                      setRegNo(p.no === "AS-PLC-100231" ? "DL-01-AB-1234" : p.no === "AS-PLC-100232" ? "MH-02-CD-5678" : "KA-03-EF-9012");
                      setMobile("9999999999");
                    }}
                  >
                    <td className="py-1 pr-2 font-mono">{p.no}</td>
                    <td className="py-1 pr-2">{p.vehicle}</td>
                    <td className="py-1">{p.idv}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </div>

      {/* Form */}
      {!verified ? (
        <div className="mt-6 space-y-4">
          <div>
            <label className="mb-1 block text-sm font-medium">Policy Number</label>
            <input
              value={policyNo}
              onChange={(e) => setPolicyNo(e.target.value)}
              placeholder="e.g. AS-PLC-100231"
              className="w-full rounded-lg border border-[#D6D0C4] px-3 py-2 text-sm focus:border-[#0F1F33] focus:outline-none"
            />
          </div>
          <div>
            <label className="mb-1 block text-sm font-medium">Vehicle Registration</label>
            <input
              value={regNo}
              onChange={(e) => setRegNo(e.target.value)}
              placeholder="e.g. DL-01-AB-1234"
              className="w-full rounded-lg border border-[#D6D0C4] px-3 py-2 text-sm focus:border-[#0F1F33] focus:outline-none"
            />
          </div>
          <div>
            <label className="mb-1 block text-sm font-medium">Mobile Number</label>
            <input
              value={mobile}
              onChange={(e) => setMobile(e.target.value)}
              placeholder="9999999999"
              className="w-full rounded-lg border border-[#D6D0C4] px-3 py-2 text-sm focus:border-[#0F1F33] focus:outline-none"
            />
          </div>
          <div>
            <label className="mb-1 block text-sm font-medium">Incident Date</label>
            <input
              type="date"
              value={incidentDate}
              onChange={(e) => setIncidentDate(e.target.value)}
              className="w-full rounded-lg border border-[#D6D0C4] px-3 py-2 text-sm focus:border-[#0F1F33] focus:outline-none"
            />
          </div>

          {!otpSent ? (
            <button
              onClick={handleSendOtp}
              className="w-full rounded-lg bg-[#0F1F33] py-2 font-semibold text-white hover:bg-[#1C3050]"
            >
              Send OTP
            </button>
          ) : (
            <div className="space-y-3">
              <div>
                <label className="mb-1 block text-sm font-medium">Enter OTP (use 123456)</label>
                <input
                  value={otpValue}
                  onChange={(e) => setOtpValue(e.target.value)}
                  maxLength={6}
                  disabled={otpLocked}
                  placeholder="123456"
                  className="w-full rounded-lg border border-[#D6D0C4] px-3 py-2 text-sm focus:border-[#0F1F33] focus:outline-none disabled:opacity-50"
                />
              </div>
              {otpError && <p className="text-sm text-red-600">{otpError}</p>}
              {!otpLocked ? (
                <button
                  onClick={handleVerifyOtp}
                  className="w-full rounded-lg bg-[#0F1F33] py-2 font-semibold text-white hover:bg-[#1C3050]"
                >
                  Verify OTP
                </button>
              ) : (
                <button
                  onClick={resetForm}
                  className="w-full rounded-lg border border-[#D6D0C4] py-2 font-semibold text-[#4A5B6B] hover:bg-[#EDE8DC]"
                >
                  Start over
                </button>
              )}
            </div>
          )}
        </div>
      ) : (
        /* Success card */
        <div className="mt-8 rounded-xl border border-[#D6D0C4] bg-white p-6">
          <div className="mb-4 flex items-center gap-3">
            <div className="flex h-10 w-10 items-center justify-center rounded-full bg-green-100 text-lg text-green-700">
              ✓
            </div>
            <div>
              <h2 className="text-lg font-semibold">Policy verified</h2>
              <p className="text-sm text-[#4A5B6B]">{policyNo}</p>
            </div>
          </div>
          <div className="rounded-lg bg-[#F6F4EE] p-4">
            <p className="text-sm font-medium">Vehicle: {regNo}</p>
            <p className="text-sm text-[#4A5B6B]">
              Incident: {new Date(incidentDate).toLocaleDateString("en-IN")}
            </p>
          </div>
          
          {apiError && <p className="mt-4 text-sm text-red-600 font-medium">{apiError}</p>}
          
          <button
            onClick={handleContinue}
            disabled={busy}
            className="mt-4 w-full rounded-lg bg-[#0F1F33] py-2 font-semibold text-white hover:bg-[#1C3050] disabled:opacity-50"
          >
            {busy ? "Connecting to AI..." : "Continue to upload"}
          </button>
        </div>
      )}
    </div>
  );
}